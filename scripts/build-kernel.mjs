#!/usr/bin/env node
/**
 * Builds the WASM word kernel of residue openings:
 *
 *   src/residue/kern.ts  (AssemblyScript source)  ->  src/residue/kernWasm.ts  (the module, base64)
 *                                                   src/residue/kern.sha256   (both hashes)
 *
 *   node scripts/build-kernel.mjs           rebuild and write both files
 *   node scripts/build-kernel.mjs --check   rebuild in memory, exit 1 unless the committed files match
 *
 * Core ships with tsc alone and consumers install it from git, so the compiled
 * bytes are committed as a TypeScript module and never built on install.
 * AssemblyScript is a devDependency pinned to one exact version, and this
 * script refuses any other: the same source and the same compiler give the
 * same bytes (checked: the output does not depend on the path or the run), so
 * anyone can rebuild and compare with --check. test/residue.test.ts asserts
 * the committed module's SHA-256 and the source's against kern.sha256 and
 * rebuilds the module the same way.
 */

import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'

export const ASSEMBLYSCRIPT_VERSION = '0.28.20'
export const ASC_FLAGS = ['-O3', '--runtime', 'stub', '--noAssert', '--memoryBase', '65536']

const root = new URL('../', import.meta.url)
const SOURCE = new URL('src/residue/kern.ts', root)
const MODULE = new URL('src/residue/kernWasm.ts', root)
const HASHES = new URL('src/residue/kern.sha256', root)

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex')

/** Compiles kern.ts with the pinned compiler and flags; resolves to the module's bytes. */
export async function compileKernel() {
  const installed = JSON.parse(readFileSync(new URL('node_modules/assemblyscript/package.json', root), 'utf8')).version
  if (installed !== ASSEMBLYSCRIPT_VERSION) {
    throw new Error(`assemblyscript ${installed} is installed; the kernel is built with exactly ${ASSEMBLYSCRIPT_VERSION} (npm ci)`)
  }
  const asc = (await import('assemblyscript/asc')).default
  let wasm = null
  const stderr = []
  const { error } = await asc.main([fileURLToPath(SOURCE), ...ASC_FLAGS, '--outFile', 'kern.wasm'], {
    writeFile(name, contents) { if (name.endsWith('kern.wasm')) wasm = new Uint8Array(contents) },
    stdout: { write() { return true } },
    stderr: { write(s) { stderr.push(String(s)); return true } },
  })
  if (error) throw new Error(`asc failed: ${error.message}\n${stderr.join('')}`)
  if (!wasm) throw new Error('asc wrote no module')
  return wasm
}

/** The text of kern.sha256 for a source and its module. */
export function hashesText(source, wasm) {
  return [
    '# Written by scripts/build-kernel.mjs; never edit by hand. test/residue.test.ts checks both lines.',
    `# assemblyscript ${ASSEMBLYSCRIPT_VERSION}: asc kern.ts ${ASC_FLAGS.join(' ')}`,
    `${sha256(source)}  kern.ts`,
    `${sha256(wasm)}  kern.wasm (the ${wasm.length} bytes of KERN_WASM_BASE64 in kernWasm.ts)`,
    '',
  ].join('\n')
}

/** The text of kernWasm.ts for a module. */
export function moduleText(wasm) {
  const b64 = Buffer.from(wasm).toString('base64')
  const lines = []
  for (let i = 0; i < b64.length; i += 100) lines.push(`  '${b64.slice(i, i + 100)}',`)
  return [
    '// kernWasm.ts - GENERATED by scripts/build-kernel.mjs from kern.ts. Never edit by hand.',
    `// assemblyscript ${ASSEMBLYSCRIPT_VERSION}: asc kern.ts ${ASC_FLAGS.join(' ')}`,
    `// ${wasm.length} bytes, sha256 ${sha256(wasm)} (also in kern.sha256).`,
    '',
    '/** The WASM word kernel (kern.ts compiled), as base64. */',
    'export const KERN_WASM_BASE64: string = [',
    ...lines,
    "].join('')",
    '',
  ].join('\n')
}

async function main() {
  const check = process.argv.includes('--check')
  const source = readFileSync(SOURCE)
  const wasm = await compileKernel()
  const files = [[MODULE, moduleText(wasm)], [HASHES, hashesText(source, wasm)]]
  if (check) {
    const stale = files.filter(([url, text]) => readFileSync(url, 'utf8') !== text).map(([url]) => fileURLToPath(url))
    if (stale.length) {
      console.error(`stale, rebuild with node scripts/build-kernel.mjs: ${stale.join(', ')}`)
      process.exit(1)
    }
    console.log(`kernel up to date: ${wasm.length} bytes, sha256 ${sha256(wasm)}`)
    return
  }
  for (const [url, text] of files) writeFileSync(url, text)
  console.log(`wrote kernWasm.ts and kern.sha256: ${wasm.length} bytes, sha256 ${sha256(wasm)}`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e) => { console.error(e); process.exit(1) })
}
